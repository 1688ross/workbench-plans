"""Generate docs/03-cut-list.md from tools/parts.py and the nesting results."""
import os, sys
sys.path.insert(0, os.path.dirname(__file__))
from parts import build, by_material, STEPS
from model import dim, frac
import render_cuts

MAT = {"BB34": '3/4" Baltic birch', "BB12": '1/2" Baltic birch', "BB14": '1/4" Baltic birch', "MDF34": '3/4" MDF', "MAPLE": "hard maple (8/4)", "PINE2x4": "2x4 SPF"}
DOC = os.path.join(os.path.dirname(__file__), "..", "docs", "03-cut-list.md")

def main():
    P = build(); summary = render_cuts.main()
    L = ["# Cut list — every piece of wood", "",
         "Generated by `tools/build_docs.py` from `tools/parts.py`; dimensions are finished sizes in inches (length x width; thickness is the material). "
         "Part IDs match the labels on the cut diagrams in `renders/cuts/`. Grain `L` means the length runs along the sheet's 96\" axis; `A` means either way is fine.", "",
         "## Sheet and board count", "", "| Material | Sheets / boards | Cut diagram |", "|---|---|---|"]
    for m in ("BB34", "BB12", "BB14", "MDF34"):
        n = summary[m]; files = ", ".join(f"[{m}-sheets-{i + 1}](../renders/cuts/{m}-sheets-{i + 1}.svg)" for i in range((n + 5) // 6))
        L.append(f"| {MAT[m]} 4x8 | **{n}** | {files} |")
    maple_area = sum(p.length * p.width * p.qty for p in P if p.material == "MAPLE") / 144
    L.append(f"| hard maple 8/4 | about **{maple_area * 2 * 1.3:.0f} board feet** (incl. 30% waste); {summary['MAPLE_boards']} pieces of 3\" x 8' shown | [MAPLE-boards](../renders/cuts/MAPLE-boards.svg) |")
    L.append("| 2x4 SPF | 2 pieces 8' | for the lift sub-platform frame |")
    L += ["", "Buy one extra sheet of 3/4\" Baltic birch: the nesting is tight (92-100% yield) and it leaves no room for a bad cut.", ""]
    # by step
    L += ["## Parts by build step", ""]
    for st in sorted(STEPS):
        ps = [p for p in P if p.step == st]
        if not ps: continue
        L += [f"### Step {st} — {STEPS[st]}", "", "| ID | Part | Qty | Length | Width | Material | Grain | Notes |", "|---|---|---|---|---|---|---|---|"]
        for p in ps:
            L.append(f"| `{p.id}` | {p.name} | {p.qty} | {dim(p.length)} | {dim(p.width)} | {MAT[p.material]} | {p.grain} | {p.note} |")
        L.append("")
    # by material
    L += ["## Parts by material (for the saw)", ""]
    for m, ps in by_material(P).items():
        L += [f"### {MAT[m]}", "", "| ID | Qty | Length | Width | Part |", "|---|---|---|---|---|"]
        for p in sorted(ps, key=lambda p: (-p.length, -p.width)):
            L.append(f"| `{p.id}` | {p.qty} | {dim(p.length)} | {dim(p.width)} | {p.name} |")
        L.append("")
    open(DOC, "w").write("\n".join(L))
    print("cut list written:", len(P), "part lines")
    return summary

if __name__ == "__main__":
    main()
